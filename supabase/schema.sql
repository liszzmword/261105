-- Block Drop profiles and score leaderboard.
-- Run this file in Supabase Dashboard > SQL Editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null check (
    char_length(username) between 2 and 16
    and username !~ '[[:space:]]'
  ),
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(username));

alter table public.profiles add column if not exists avatar_path text;
alter table public.profiles add column if not exists avatar_generation_window_start timestamptz;
alter table public.profiles add column if not exists avatar_generation_count integer not null default 0;

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  score integer not null check (score between 0 and 10000000),
  level integer not null check (level between 1 and 99),
  lines integer not null check (lines between 0 and 10000),
  difficulty text not null check (difficulty in ('easy', 'normal', 'hard')),
  created_at timestamptz not null default now()
);

create index if not exists scores_user_best_idx
  on public.scores (user_id, score desc, created_at asc);

alter table public.profiles enable row level security;
alter table public.scores enable row level security;

revoke all on table public.profiles from anon, authenticated;
revoke all on table public.scores from anon, authenticated;
grant select on table public.profiles to anon, authenticated;
grant update (avatar_path) on table public.profiles to authenticated;
grant select on table public.scores to anon, authenticated;
grant insert on table public.scores to authenticated;
grant usage, select on sequence public.scores_id_seq to authenticated;

drop policy if exists "Anyone can read player names" on public.profiles;
create policy "Anyone can read player names"
  on public.profiles for select
  to anon, authenticated
  using (true);

drop policy if exists "Players can update their own avatar" on public.profiles;
create policy "Players can update their own avatar"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()) and (avatar_path is null or avatar_path like id::text || '/%.webp'));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 5242880, array['image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/webp'];

drop policy if exists "Players can upload their own avatar" on storage.objects;
create policy "Players can upload their own avatar"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text and lower(storage.extension(name)) = 'webp');

drop policy if exists "Players can remove their own avatar" on storage.objects;
create policy "Players can remove their own avatar"
  on storage.objects for delete to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = (select auth.uid())::text);

create or replace function public.claim_avatar_generation()
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed boolean;
begin
  if auth.uid() is null then return false; end if;
  update public.profiles
  set avatar_generation_window_start = case
        when avatar_generation_window_start is null or avatar_generation_window_start <= now() - interval '24 hours' then now()
        else avatar_generation_window_start end,
      avatar_generation_count = case
        when avatar_generation_window_start is null or avatar_generation_window_start <= now() - interval '24 hours' then 1
        else avatar_generation_count + 1 end
  where id = auth.uid()
    and (avatar_generation_window_start is null or avatar_generation_window_start <= now() - interval '24 hours' or avatar_generation_count < 3)
  returning true into claimed;
  return coalesce(claimed, false);
end;
$$;
revoke all on function public.claim_avatar_generation() from public, anon;
grant execute on function public.claim_avatar_generation() to authenticated;

drop policy if exists "Anyone can read scores" on public.scores;
create policy "Anyone can read scores"
  on public.scores for select
  to anon, authenticated
  using (true);

drop policy if exists "Players can submit their own scores" on public.scores;
create policy "Players can submit their own scores"
  on public.scores for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and score between 0 and 10000000
    and level between 1 and 99
    and lines between 0 and 10000
    and difficulty in ('easy', 'normal', 'hard')
  );

create or replace function public.create_blockdrop_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_name text;
begin
  requested_name := nullif(btrim(new.raw_user_meta_data ->> 'username'), '');
  if requested_name is null then
    requested_name := 'player_' || substr(new.id::text, 1, 8);
  end if;

  insert into public.profiles (id, username)
  values (new.id, requested_name);
  return new;
end;
$$;

revoke all on function public.create_blockdrop_profile() from public, anon, authenticated;
drop trigger if exists on_auth_user_created_blockdrop on auth.users;
create trigger on_auth_user_created_blockdrop
  after insert on auth.users
  for each row execute function public.create_blockdrop_profile();

create or replace view public.leaderboard
with (security_invoker = true)
as
select
  row_number() over (order by personal_best.score desc, personal_best.created_at asc) as rank,
  personal_best.user_id,
  players.username,
  personal_best.score,
  personal_best.level,
  personal_best.difficulty,
  personal_best.created_at,
  players.avatar_path
from (
  select distinct on (game_scores.user_id)
    game_scores.user_id,
    game_scores.score,
    game_scores.level,
    game_scores.difficulty,
    game_scores.created_at
  from public.scores as game_scores
  order by game_scores.user_id, game_scores.score desc, game_scores.created_at asc
) as personal_best
join public.profiles as players on players.id = personal_best.user_id;

grant select on public.leaderboard to anon, authenticated;
